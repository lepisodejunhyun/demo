/**
 * ============================================================
 * [ Request DTO란? ]
 * 1. 개념: 클라이언트가 서버로 "요청 본문(body)에 담아 보내는" 데이터의 형태를 정의하는 클래스.
 *
 * 2. Response DTO(admin.dto.ts)와의 차이:
 *    Response DTO → 서버 → 클라이언트 (응답에 어떤 필드를 포함할지 = 직렬화)
 *    Request DTO  → 클라이언트 → 서버 (요청에 어떤 값이 들어와야 하는지 = 검증)
 *
 * 3. 전체 흐름:
 *    [1] 클라이언트가 JSON 보냄 → { "email": "...", "password": "..." }
 *    [2] NestJS의 @Body()가 이 DTO 타입으로 변환 (plain object → DTO instance)
 *    [3] ValidationPipe(main.ts에 등록)가 자동으로 각 데코레이터 규칙 검증
 *    [4] 통과 → Controller 핸들러 실행 / 실패 → 자동 400 응답 + 에러 메시지
 *
 * [ 이 파일에서 배울 수 있는 핵심 개념 ]
 * 1. class-validator 라이브러리 — 데코레이터 기반 입력 검증
 * 2. 데코레이터 스택(쌓기) 메커니즘 — 여러 데코레이터가 동시에 적용되는 원리
 * 3. @IsNotEmpty / @IsEmail / @IsString — 기본 검증 데코레이터
 * 4. @MinLength / @MaxLength            — 길이 제약
 * 5. @Matches(정규식)                   — 정규식 기반 패턴 검증
 * 6. 정규식(Regex) 기본 문법
 * 7. 전방 탐색(Lookahead) 기법
 * 8. message 옵션                       — 검증 실패 시 클라이언트에 보낼 에러 메시지
 *
 * [ main.ts 및 admin.controller.ts와의 연결 ]
 * - main.ts: app.useGlobalPipes(new ValidationPipe({...}))로 전역 검증 활성화
 * - admin.controller.ts: async signin(@Body() data: AdminSignInDTO)
 *   → 타입만 지정하면 ValidationPipe가 자동으로 이 DTO의 규칙을 적용함.
 *
 * [ ValidationPipe가 정확히 어떻게 동작하는가? ]
 * 1. @Body() data: AdminSignInDTO를 만나면 NestJS가:
 *    a) 받은 JSON을 AdminSignInDTO 클래스 인스턴스로 변환 (plainToInstance)
 *    b) reflect-metadata로 각 필드의 데코레이터 목록을 읽음
 *    c) class-validator의 validate() 함수로 모든 규칙 검사
 *    d) 하나라도 실패하면 BadRequestException(400) 자동 throw
 * 2. 결과: 컨트롤러 함수에 들어올 때는 100% 검증 통과된 데이터만 들어옴.
 * ============================================================
 */

import { ApiProperty } from "@nestjs/swagger";
import { IsNotEmpty, IsEmail, IsString, MinLength, MaxLength, Matches } from "class-validator";

export class AdminSignInDTO {
  /**
   * ============================================================
   * [ 데코레이터 스택(여러 데코레이터를 한 필드에 쌓기) ]
   *
   * 1. 동작 원리:
   *    한 필드 위에 데코레이터를 여러 개 쌓으면, "AND 조건"으로 모두 적용됨.
   *    하나라도 실패하면 즉시 그 message가 클라이언트에 반환됨.
   *
   * 2. 실행 순서:
   *    데코레이터는 위에서 아래로 등록되지만, validate() 시점에는
   *    class-validator가 모든 규칙을 모아서 한 번에 평가.
   *    → 결과적으로 "모든 규칙 통과" 또는 "첫 실패 메시지 반환".
   *
   * 3. message 옵션의 역할:
   *    - 검증 실패 시 클라이언트가 받게 될 사용자용 에러 메시지.
   *    - 한국어 메시지를 명시해두면 프론트엔드가 그대로 화면에 표시 가능.
   *    - 생략 시 영어 기본 메시지(예: "email must be an email")가 노출됨.
   *
   * [ 각 데코레이터의 의미 ]
   *
   * @ApiProperty — Swagger 문서용 (검증 무관, 문서화 전용. admin.dto.ts 참고).
   *
   * @IsNotEmpty — 값이 null/undefined/빈 문자열('')이면 실패.
   *   주의: 0이나 false는 비어있지 않은 값으로 간주됨.
   *
   * @IsEmail({}, { message: ... })
   *   - 첫 번째 인자 {}: 옵션 객체 (도메인 화이트리스트 allowlist, IP 도메인 허용 여부 등).
   *     비워두면 기본 규칙으로 "xxx@xxx.xxx" 형태 검증.
   *   - 두 번째 인자: 메시지 옵션.
   *   - 빈 문자열로 들어오면 @IsNotEmpty가 먼저 막아서 여기까진 안 옴.
   * ============================================================
   */
  @ApiProperty({ description: '관리자 이메일' })
  @IsNotEmpty({ message: '이메일은 필수 입력 항목입니다.' })
  @IsEmail({}, { message: '올바른 이메일 형식이 아닙니다.' })
  email: string;

  /**
   * ============================================================
   * [ 비밀번호 검증 — 여러 데코레이터 조합 ]
   *
   * 검증 규칙 (모두 통과해야 OK):
   *   1. @IsNotEmpty   → 비어있지 않음
   *   2. @IsString     → 문자열 타입 (숫자/배열 거부)
   *   3. @MinLength(8) → 8자 이상
   *   4. @MaxLength(16) → 16자 이하
   *   5. @Matches(정규식) → 영문 + 숫자 + 특수문자 모두 포함
   *
   * 만약 7자를 보내면 → @MinLength의 message가 반환되어
   *   클라이언트가 "비밀번호는 최소 8자 이상이어야 합니다." 메시지를 받음.
   *
   * 왜 길이 검증과 패턴 검증을 분리했는가?
   *   - 통합 정규식으로도 가능하지만, 분리하면 어느 규칙에서 실패했는지
   *     명확한 메시지를 줄 수 있음 → 사용자 경험 향상.
   *   - 예: "8자 이상이어야 합니다" vs "복잡한 정규식 안 맞음"
   *
   * ============================================================
   * [ 정규식(Regular Expression)이란? ]
   * 1. 개념: 문자열의 패턴을 표현하는 작은 미니 언어.
   *          "이런 모양의 문자열이냐?"를 한 줄로 표현.
   *
   * 2. 기본 문법 (자주 쓰는 것):
   *    /pattern/   → 정규식은 슬래시로 감쌈
   *    ^           → 문자열의 시작
   *    $           → 문자열의 끝
   *    .           → 아무 문자 한 글자
   *    \d          → 숫자 한 글자 (= [0-9])
   *    \s          → 공백 문자
   *    [abc]       → a 또는 b 또는 c 중 하나
   *    [A-Za-z]    → 영문자 한 글자
   *    *           → 0번 이상 반복
   *    +           → 1번 이상 반복
   *    ?           → 0 또는 1번
   *    {3,5}       → 3~5번 반복
   *
   * 3. 비유:
   *    "이메일 형식인가?"를 if문으로 짜려면 수십 줄.
   *    정규식으로는 한 줄. 패턴 검사의 표준 도구.
   *
   * ============================================================
   * [ 이 비밀번호 정규식 분석 ]
   * /^(?=.*[A-Za-z])(?=.*\d)(?=.*[특수문자들])/
   *
   *   ^                  → 문자열 시작
   *   (?=.*[A-Za-z])     → 어딘가에 영문자 1개 이상 (긍정형 전방 탐색)
   *   (?=.*\d)           → 어딘가에 숫자 1개 이상 (전방 탐색)
   *   (?=.*[특수문자])   → 어딘가에 특수문자 1개 이상 (전방 탐색)
   *
   * [ 전방 탐색(Lookahead) — (?=...) 문법 ]
   * 1. 개념: "이 위치 뒤에 이런 패턴이 있는지 확인만 하고, 실제로는 진행하지 않음"
   *          → 매칭 위치를 소비하지 않는 "엿보기" 검사.
   *
   * 2. 왜 필요한가?
   *    - 일반 정규식은 "왼쪽에서 오른쪽으로" 순차 매칭.
   *      "영문 다음 숫자 다음 특수문자" 같은 순서가 강제됨.
   *    - 하지만 비밀번호는 "어떤 순서로든 셋 다 들어 있으면 OK"이 조건.
   *    - 전방 탐색을 쓰면 "어딘가에 X가 존재"를 독립적으로 여러 번 검사 가능.
   *
   * 3. 동작 예시 — "abc123!" 검사:
   *    [1] ^에서 시작
   *    [2] (?=.*[A-Za-z]) → 뒤를 보니 'a' 존재. OK. 위치는 그대로 ^.
   *    [3] (?=.*\d)       → 뒤를 보니 '1' 존재. OK. 위치는 그대로 ^.
   *    [4] (?=.*[특수])   → 뒤를 보니 '!' 존재. OK. 통과.
   *
   * 4. 주의 — 이 정규식은 길이 검사를 하지 않음:
   *    "ab1!"도 패턴 자체는 통과. 길이 검증은 @MinLength/@MaxLength에 맡김.
   *    → 책임 분리: 각 규칙이 하나의 관심사만 다룸.
   *
   * 5. 특수문자 클래스 안의 \문자들:
   *    [\{\}\[\]\/?.,;:|\)*~`!^\-_+<>@\#$%&\\\=\(\'\"]
   *    - 정규식에서 특별한 의미를 가진 문자들({ } [ ] / 등)은 \로 이스케이프.
   *    - \-는 문자 클래스 내에서 범위(예: A-Z)의 - 와 구분하기 위해 이스케이프.
   * ============================================================
   */
  @ApiProperty({ description: '관리자 비밀번호' })
  @IsNotEmpty({ message: '비밀번호는 필수 입력 항목입니다.' })
  @IsString()
  @MinLength(8, { message: '비밀번호는 최소 8자 이상이어야 합니다.' })
  @MaxLength(16, { message: '비밀번호는 최대 16자 이하이어야 합니다.' })
  @Matches(/^(?=.*[A-Za-z])(?=.*\d)(?=.*[\{\}\[\]\/?.,;:|\)*~`!^\-_+<>@\#$%&\\\=\(\'\"])/, {
    message: '비밀번호는 영문, 숫자, 특수문자가 모두 포함되어야 합니다.',
  })
  password: string;
}
